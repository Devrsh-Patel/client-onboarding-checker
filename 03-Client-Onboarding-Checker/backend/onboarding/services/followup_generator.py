"""
Follow-Up Message Generator
Generates polite, client-ready follow-up drafts based strictly on confirmed findings
and verified submissions. Never hallucinates commitments, deadlines, or exposed secrets.
"""

from typing import Dict, Any
from onboarding.models import OnboardingCase, FollowUpMessage, Finding, SubmissionItem


def generate_follow_up_message(case: OnboardingCase) -> FollowUpMessage:
    """
    Constructs a professional follow-up email/letter draft grouping
    confirmed missing items, incomplete submissions, and clarification questions.
    """
    client = case.client
    recipient = client.contact_person or "Client Team"
    project_name = case.project_name

    # Fetch active findings grouped by category
    open_findings = case.findings.filter(status='open')
    missing_items = open_findings.filter(finding_type='missing_item')
    incomplete_items = open_findings.filter(finding_type='incomplete_submission')
    questions = open_findings.filter(finding_type__in=['question', 'unclear_requirement'])
    security_alerts = open_findings.filter(finding_type='security_concern')

    # Subject line
    subject = f"Scalezix Onboarding — Next Steps & Material Checklist for {project_name}"

    # Greeting
    greeting = f"Hi {recipient}," if client.contact_person else "Hello Team,"

    # Build structured body text
    body_parts = [
        f"{greeting}",
        "",
        (
            f"Thank you for kicking off the onboarding process for **{project_name}** with Scalezix Ventures. "
            "Our engineering and operations team has reviewed the initial materials submitted to date. "
            "To ensure a seamless kickoff and avoid timeline delays, we have outlined the items still needed below."
        ),
        "",
    ]

    # Section 1: Missing Required Items
    if missing_items.exists():
        body_parts.append("### 1. Outstanding Required Materials")
        body_parts.append("The following items are essential for project setup and have not yet been received:")
        for idx, item in enumerate(missing_items, 1):
            cl_title = item.checklist_item.title if item.checklist_item else item.title
            evidence = item.checklist_item.acceptable_evidence if item.checklist_item else ""
            desc = f" — *Accepted formats: {evidence}*" if evidence else ""
            body_parts.append(f"{idx}. **{cl_title}**{desc}")
        body_parts.append("")

    # Section 2: Incomplete or Needs Revision
    if incomplete_items.exists():
        body_parts.append("### 2. Submissions Requiring Completion or Clarification")
        body_parts.append("We received initial files for the following, but require additional components:")
        for idx, item in enumerate(incomplete_items, 1):
            cl_title = item.checklist_item.title if item.checklist_item else item.title
            body_parts.append(f"- **{cl_title}**: {item.explanation}")
        body_parts.append("")

    # Section 3: Technical & Scope Clarifications
    if questions.exists():
        body_parts.append("### 3. Questions for Your Technical / Project Lead")
        for idx, item in enumerate(questions, 1):
            body_parts.append(f"{idx}. {item.title}: {item.explanation}")
        body_parts.append("")

    # Section 4: Security & Credential Sharing Guidance (if applicable)
    if security_alerts.exists():
        body_parts.append("### 4. Important Note Regarding Credential Sharing")
        body_parts.append(
            "⚠️ **Security Notice**: For your team's protection, please do not email passwords, "
            "API secret keys, or database credentials directly in plain text or documents. "
            "Our team will provide a secure, encrypted vault link (or you may invite us via 1Password / AWS IAM / Bitwarden) "
            "to exchange production access safely."
        )
        body_parts.append("")

    # Section 5: Next Steps & Closing
    body_parts.append("### Next Steps")
    body_parts.append(
        "Please review the items above and upload or reply with the remaining materials at your earliest convenience. "
        "If you have any questions or require assistance generating any of these assets, please let us know."
    )
    body_parts.append("")
    body_parts.append("Warm regards,")
    body_parts.append("The Scalezix Client Operations Team")
    body_parts.append("Scalezix Ventures LLP | operations@scalezix.com")
    body_parts.append("")
    body_parts.append("> *Notice: This message is a draft generated by the Client Onboarding Assistant. Review and confirm all details before sending to the client.*")

    full_body = "\n".join(body_parts)

    # Save or update FollowUpMessage
    message, created = FollowUpMessage.objects.update_or_create(
        case=case,
        defaults={
            'recipient_name': recipient,
            'subject': subject,
            'greeting': greeting,
            'body': full_body,
            'status': 'draft',
        }
    )

    return message

